/** Writes a number with a fixed number of decimals, the English way (2.1). */
const decimals = (value: number, digits: number) =>
  value.toLocaleString('en-CA', { minimumFractionDigits: digits, maximumFractionDigits: digits });

/** Agrees a noun with a number: "1 tube", "3 tubes". */
const plural = (count: number, one: string, many: string) =>
  `${count.toLocaleString('en-CA')} ${count === 1 ? one : many}`;

